/**
 * Extract Over Ons + cinematic hero mobile CSS from React src/styles.css
 * into ipekci-theme/assets/css/ons-verhaal-mobile.css
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const ROOT = resolve(import.meta.dirname, '..');
const src = readFileSync(resolve(ROOT, 'src/styles.css'), 'utf8');
const lines = src.split('\n');

function slice(start, end) {
  return lines.slice(start - 1, end).join('\n');
}

// Cinematic hero desktop base (inside components layer, 2-space indent → strip)
const cinematicBase = slice(3605, 3672)
  .split('\n')
  .map((l) => l.replace(/^  /, ''))
  .join('\n');

// Mobile block content: pick line ranges inside @media (max-width: 767px) at ~4223
const mobileChunks = [
  [4287, 4425], // cinematic hero mobile
  [4552, 4579], // sticky bar + body padding
  [4647, 6293], // over ons hero lede + all ons-*-app modules + desktop mobile tweaks
];

const mobileInner = mobileChunks
  .map(([s, e]) => slice(s, e))
  .join('\n\n')
  .split('\n')
  .map((l) => (l.startsWith('    ') ? l.slice(2) : l.replace(/^  /, '')))
  .join('\n');

const header = `/**
 * Over Ons — mobile app UI + cinematic hero (React src/styles.css parity).
 * Generated by scripts/extract-ons-mobile-css.mjs — re-run after React CSS changes.
 *
 * @package Ayat_Food
 */

/* Layout utilities — dual mobile/desktop modules (Tailwind lg breakpoint) */
@media (max-width: 1023px) {
\t.ipekci-ov-desktop-only {
\t\tdisplay: none !important;
\t}
}

@media (min-width: 1024px) {
\t.ipekci-ov-mobile-only {
\t\tdisplay: none !important;
\t}
}

`;

const out =
  header +
  cinematicBase +
  '\n\n@media (max-width: 767px) {\n' +
  mobileInner +
  '\n}\n';

const dest = resolve(ROOT, 'ipekci-theme/assets/css/ons-verhaal-mobile.css');
writeFileSync(dest, out);
console.log(`Wrote ${dest} (${out.length} bytes)`);
