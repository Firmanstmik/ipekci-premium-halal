/**
 * Extract Vacatures mobile CSS from React src/styles.css
 * into ipekci-theme/assets/css/vacatures-mobile.css
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const ROOT = resolve(import.meta.dirname, '..');
const src = readFileSync(resolve(ROOT, 'src/styles.css'), 'utf8');
const lines = src.split('\n');

function slice(start, end) {
  return lines.slice(start - 1, end).join('\n');
}

const cinematicBase = slice(3651, 3718)
  .split('\n')
  .map((l) => l.replace(/^  /, ''))
  .join('\n');

const mobileChunks = [
  [4333, 4471],
  [6117, 6534],
];

const mobileInner = mobileChunks
  .map(([s, e]) => slice(s, e))
  .join('\n\n')
  .split('\n')
  .map((l) => (l.startsWith('    ') ? l.slice(2) : l.replace(/^  /, '')))
  .join('\n');

const header = `/**
 * Vacatures — mobile app UI + cinematic hero (React src/styles.css parity).
 * Generated by scripts/extract-vacatures-mobile-css.mjs
 *
 * @package Ayat_Food
 */

@media (max-width: 767px) {
	.ipekci-vac-desktop-only {
		display: none !important;
	}
}

@media (min-width: 768px) {
	.ipekci-vac-mobile-only {
		display: none !important;
	}
}

`;

const out =
  header +
  cinematicBase +
  '\n\n@media (max-width: 767px) {\n' +
  mobileInner +
  '\n}\n';

const dest = resolve(ROOT, 'ipekci-theme/assets/css/vacatures-mobile.css');
writeFileSync(dest, out);
console.log(`Wrote ${dest} (${out.length} bytes)`);
